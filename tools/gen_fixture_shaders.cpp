// gen_fixture_shaders: writes tests/fixtures/triangle_shaders.h (DXBC for the triangle fixture) from tests/dxbc_builder.h.
// Usage: gen_fixture_shaders [triangle|scene] > tests/fixtures/<name>_shaders.h   (default: triangle)
#include <cstdio>
#include <string>
#include <vector>
#include "dxbc_builder.h"
static void emit(const char* name, const std::vector<uint8_t>& b) {
  std::printf("static const unsigned char %s[%zu] = {", name, b.size());
  for (size_t i = 0; i < b.size(); i++) std::printf("%s%u,", i % 16 == 0 ? "\n  " : "", b[i]);
  std::printf("\n};\n");
}
int main(int argc, char** argv) {
  bool scene = argc > 1 && std::string(argv[1]) == "scene";
  std::printf("/* Generated by tools/gen_fixture_shaders.cpp from tests/dxbc_builder.h. Hand-built DXBC, not Microsoft output. */\n");
  if (scene) {
    emit("scene_vs_cb", dxb::vs_cb_scale_offset());
    emit("scene_ps_cb", dxb::ps_cb_tint());
    emit("scene_vs_tex", dxb::vs_tex_pass());
    emit("scene_ps_tex", dxb::ps_sample());
  } else {
    emit("triangle_vs", dxb::vs_color_pass());
    emit("triangle_ps", dxb::ps_pass());
  }
  return 0;
}
